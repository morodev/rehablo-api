import assert from 'node:assert/strict';
import {randomBytes, randomUUID} from 'node:crypto';
import {createRequire} from 'node:module';
import type {Server} from 'node:http';
import express from 'express';
import jwt from 'jsonwebtoken';
import dotenv from 'dotenv';
import type {Sequelize} from 'sequelize';

type FixtureActor = {userId: string; tenantId: string; structureId: string | null; actor?: 'staff' | 'patient'; patientAccessId?: string};
export type ApiResult = {status: number; body: any};

export async function createActivitiesHarness() {
    // Nothing importing config/database.ts may be loaded until this guard succeeds.
    dotenv.config();
    const {requireActivitiesTestDatabase} = await import('../../../../scripts/activities-test-database.mjs');
    const safeDatabase = requireActivitiesTestDatabase(process.env);
    process.env.DATABASE_URL = safeDatabase.databaseUrl;
    process.env.NODE_ENV = 'test';
    process.env.JWT_SECRET = randomBytes(32).toString('hex');
    process.env.DB_SSL = 'false';
    process.env.TENANT_SCHEMA_SYNC = 'additive';

    const {sequelize} = await import('../../../config/database.js');
    (sequelize as Sequelize & {options: {logging: false | ((sql: string) => void)}}).options.logging = false;

    const auth = await import('../../auth/models/index.js');
    const tenantSchema = await import('../../../utils/tenantSchema.js');
    const migrations = await import('../../../utils/tenantMigrations.js');
    const activities = await import('../models/index.js');
    const notes = await import('../../notes/models/index.js');
    const {registerTenantModels} = await import('../../../tenantModelsRegistry.js');

    const run = randomUUID();
    const tenantA = randomUUID();
    const tenantB = randomUUID();
    const structureA = randomUUID();
    const structureA2 = randomUUID();
    const structureB = randomUUID();
    const ownerA = randomUUID();
    const therapistA = randomUUID();
    const viewerA = randomUUID();
    const outsiderA = randomUUID();
    const ownerB = randomUUID();
    const patientAccessId = randomUUID();
    const userIds = [ownerA, therapistA, viewerA, outsiderA, ownerB];
    const tenantIds = [tenantA, tenantB];
    const structureIds: string[] = [structureA, structureA2, structureB];
    const schemaA = tenantSchema.getTenantSchemaName(tenantA);
    const schemaB = tenantSchema.getTenantSchemaName(tenantB);
    const extraSchemas: string[] = [];
    let server: Server | undefined;
    let baseUrl = '';
    let verifiedDatabase = false;

    const cleanup = async () => {
        if (server) {
            await new Promise<void>((resolve, reject) => {
                server!.close(error => error ? reject(error) : resolve());
                server!.closeAllConnections();
            });
            server = undefined;
        }
        if (!verifiedDatabase) {
            await sequelize.close();
            return;
        }
        try {
            // Every removed schema/row belongs to UUIDs generated by this fixture run.
            for (const schema of [schemaA, schemaB, ...extraSchemas]) {
                assert.match(schema, /^rehablo_[a-f0-9]{32}$/);
                await sequelize.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
            }
            await auth.PatientPortalAccess.destroy({where: {id: patientAccessId}});
            await auth.StructureUser.destroy({where: {structureId: structureIds}});
            await auth.TenantUser.destroy({where: {tenantId: tenantIds}});
            await auth.StructureAvailability.destroy({where: {structureId: structureIds}});
            await auth.Structure.destroy({where: {id: structureIds}});
            await auth.UserEmail.destroy({where: {userId: userIds}});
            await auth.User.destroy({where: {id: userIds}});
            await auth.Tenant.destroy({where: {id: tenantIds}});
        } finally {
            await sequelize.close();
        }
    };

    try {
        await sequelize.authenticate();
        const [databaseRows] = await sequelize.query('SELECT current_database() AS name');
        assert.equal((databaseRows[0] as {name: string}).name, safeDatabase.databaseName);
        verifiedDatabase = true;
        auth.registerAuthAssociations();
        await auth.syncAuthModels();
        const {syncBillingModels} = await import('../../billing/models/billing.model.js');
        await syncBillingModels();
        // Public calendar tables are normally provisioned by startup migration; this harness owns an isolated test DB.
        await auth.StructureUserAvailability.sync();
        await auth.CalendarPreference.sync();
        registerTenantModels();
        for (const id of tenantIds) {
            await auth.Tenant.create({id, businessName: `Activities test ${id}`, license: 'activities-integration-test',
                idStripe: `activities-test-${id}`, isActive: true, maxUserQuantity: 10, maxStructureQuantity: 10});
        }
        for (const [id, tenantId] of [[structureA, tenantA], [structureA2, tenantA], [structureB, tenantB]]) {
            await auth.Structure.create({id, tenantId, name: `Activities test ${id}`});
        }
        for (const id of userIds) {
            await auth.User.create({id, email: `activities-${run}-${id}@example.invalid`, password: 'not-a-login-password',
                name: 'Integration', surname: id.slice(0, 8), isActive: true});
        }
        await auth.TenantUser.bulkCreate([
            {tenantId: tenantA, userId: ownerA, role: 'OWNER'},
            {tenantId: tenantA, userId: therapistA, role: 'THERAPIST'},
            {tenantId: tenantA, userId: viewerA, role: 'VIEWER'},
            {tenantId: tenantA, userId: outsiderA, role: 'THERAPIST'},
            {tenantId: tenantB, userId: ownerB, role: 'OWNER'}
        ]);
        await auth.StructureUser.bulkCreate([
            {structureId: structureA, userId: ownerA}, {structureId: structureA2, userId: ownerA},
            {structureId: structureA, userId: therapistA, calendarEnabled: false},
            {structureId: structureA, userId: viewerA},
            {structureId: structureA2, userId: outsiderA}, {structureId: structureB, userId: ownerB}
        ]);
        await tenantSchema.ensureTenantSchema(tenantA);
        await tenantSchema.ensureTenantSchema(tenantB);

        // A patient actor needs a real active portal context. Keep the same identity as
        // ownerA to exercise switching between staff and patient contexts (including device logout).
        const {default: Patient} = await import('../../patients/models/patient.model.js');
        const patient = await Patient.schema(schemaA).create({tenantId: tenantA, structureId: structureA,
            userId: ownerA, name: 'Portal', surname: `Fixture ${run}`});
        await auth.PatientPortalAccess.create({id: patientAccessId, userId: ownerA, tenantId: tenantA,
            patientId: patient.id, status: 'ACTIVE'});

        const {default: router} = await import('../routes/activities.routes.js');
        const {default: notificationsRouter} = await import('../routes/activityNotifications.routes.js');
        const {errorHandler, notFoundHandler} = await import('../../../middleware/errorHandler.js');
        const {default: authRouter} = await import('../../auth/routes/auth.routes.js');
        const app = express();
        app.use(express.json());
        app.use(notificationsRouter);
        app.use(router);
        app.use(authRouter);
        app.use(notFoundHandler);
        app.use(errorHandler);
        server = await new Promise<Server>(resolve => {
            const listener = app.listen(0, '127.0.0.1', () => resolve(listener));
        });
        const address = server.address();
        assert.ok(address && typeof address !== 'string');
        baseUrl = `http://127.0.0.1:${address.port}`;
    } catch (error) {
        try {await cleanup();} catch { /* Preserve the original setup failure; close runs in finally. */ }
        throw error;
    }

    const actors = {
        ownerA: {userId: ownerA, tenantId: tenantA, structureId: structureA},
        ownerA2: {userId: ownerA, tenantId: tenantA, structureId: structureA2},
        therapistA: {userId: therapistA, tenantId: tenantA, structureId: structureA},
        viewerA: {userId: viewerA, tenantId: tenantA, structureId: structureA},
        outsiderA: {userId: outsiderA, tenantId: tenantA, structureId: structureA},
        ownerB: {userId: ownerB, tenantId: tenantB, structureId: structureB},
        missingStructure: {userId: ownerA, tenantId: tenantA, structureId: null},
        foreignStructure: {userId: ownerA, tenantId: tenantA, structureId: structureB},
        patient: {userId: ownerA, tenantId: tenantA, structureId: structureA, actor: 'patient', patientAccessId}
    } satisfies Record<string, FixtureActor>;

    const token = (actor: FixtureActor) => jwt.sign({
        id: actor.userId, sub: actor.userId, email: 'integration@example.invalid', isActive: true, isSuperAdmin: false,
        tenants: [{id: actor.tenantId}], tid: actor.tenantId, sid: actor.structureId,
        selectedPremise: actor.structureId ? {id: actor.structureId} : null,
        actor: actor.actor ?? 'staff', tokenUse: 'application',
        ...(actor.patientAccessId ? {patientAccessId: actor.patientAccessId} : {}),
        // Deliberately stale/overpowered claims: the real Activities context must recheck database policy.
        role: 'OWNER', perms: ['activity:manage:tenant', 'structure:manage:tenant', 'user:manage:tenant']
    }, process.env.JWT_SECRET!, {expiresIn: '1h'});

    const api = async (actor: FixtureActor | null, method: string, path: string, body?: unknown): Promise<ApiResult> => {
        const headers: Record<string, string> = {'content-type': 'application/json'};
        if (actor) headers.authorization = `Bearer ${token(actor)}`;
        const response = await fetch(baseUrl + path, {method, headers,
            body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(30_000)});
        return {status: response.status, body: await response.json()};
    };

    const require = createRequire(import.meta.url);
    const activitiesMigration = require('../../../../migrations/20261011-activities-foundation.js') as {
        up(queryInterface: ReturnType<Sequelize['getQueryInterface']>, options: {schema: string; transaction?: any}): Promise<void>
    };

    return {sequelize, auth, activities, notes, migrations, activitiesMigration, tenantSchema, actors, api, cleanup, baseUrl,
        testDatabaseUrl: safeDatabase.databaseUrl,
        extraSchemas,
        trackStructure: (id: string) => {
            assert.match(id, /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/);
            if (!structureIds.includes(id)) structureIds.push(id);
        },
        ids: {tenantA, tenantB, structureA, structureA2, structureB, ownerA, therapistA, viewerA, outsiderA, ownerB},
        schemas: {a: schemaA, b: schemaB}};
}

export type ActivitiesHarness = Awaited<ReturnType<typeof createActivitiesHarness>>;
